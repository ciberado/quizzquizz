  echo "   ✗ Player app not running on port 3002"
  echo "   Start it with: npm run dev --workspace=@quizzquizz/player-app"
  exit 1
fi
echo "   ✓ Player app server is running"

# Run unit tests
echo ""
echo "3. Running component unit tests..."
cd /workspaces/quizzquizz
npm test -- --run --workspace=@quizzquizz/player-app 2>&1 | grep -E "(PASS|FAIL|Test|✓|✗)" || true

