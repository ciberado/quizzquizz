#!/bin/bash
# Manual test script for Phase 4B - Join & Lobby Screens
# Tests the complete join flow with actual API integration

set -e

echo "=== Phase 4B Testing: Join & Lobby Screens ==="
echo ""

# Check if API server is running
echo "1. Checking API server..."
if ! curl -s -o /dev/null -w "%{http_code}" http://localhost:3000/health | grep -q "200"; then
  echo "   ✗ API server not running on port 3000"
  echo "   Start it with: npm run dev --workspace=@quizzquizz/api-server"
  exit 1
fi
echo "   ✓ API server is running"

# Check if player app is running
echo ""
echo "2. Checking player app server..."
